import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
let Panel;
const context = vm.createContext({HTMLElement: class {}, customElements: {get: () => undefined, define: (_name, value) => { Panel = value; }}, Intl});
vm.runInContext(fs.readFileSync("custom_components/vless_gateway/frontend/src/vless-gateway-panel.js", "utf8"), context);
const panel = Object.create(Panel.prototype);
panel._panel = {config: {entity_roles: {routed_traffic: "sensor.actual_total"}}};
panel._hass = {states: {"sensor.actual_total": {state: "150", attributes: {unit_of_measurement: "B"}}}};
const html = panel._renderTraffic();
assert.ok(html.includes("Трафик sing-box"), "DIRECT-inclusive total must describe its measured scope");
assert.ok(html.includes("DIRECT") && html.includes("VLESS") && html.toLowerCase().includes("обход"), "scope must distinguish kernel bypass");
assert.ok(!html.includes("Через VLESS") && !html.includes("защищённого"));
for (const [state, tone, label] of [["degraded_fail_open", "warn", "DIRECT: резервный режим"], ["control_error", "bad", "Ошибка управления"], ["starting", "warn", "Запуск"]]) {
 assert.equal(panel._stateTone(state), tone);
 assert.equal(panel._displayState({state}), label);
}
console.log("Factual traffic scope and gateway failure states passed");

// These snapshots are generated by the gateway controller's behavioral contract test.
const fixture = (name) => JSON.parse(fs.readFileSync(`tests/fixtures/api_v1/${name}.json`, "utf8")).data;
const before = fixture("status-confirmed-change");
for (const name of ["status-direct-tunnel-failed", "status-selector-unconfirmed"]) {
 const data = fixture(name);
 const metricState = (metric) => metric.available ? (typeof metric.value === "boolean" ? (metric.value ? "on" : "off") : metric.value) : "unavailable";
 panel._panel = {config: {entity_roles: {gateway_status: "sensor.gateway", tunnel_status: "binary_sensor.tunnel", active_route: "sensor.route", last_route_change: "sensor.change"}}};
 panel._hass = {states: {
  "sensor.gateway": {state: data.state, attributes: {}},
  "binary_sensor.tunnel": {state: metricState(data.tunnel_status), attributes: {}},
  "sensor.route": {state: metricState(data.active_route), attributes: {}},
  "sensor.change": {state: data.last_route_change?.at || "unknown", attributes: {}},
 }};
 assert.notEqual(panel._roleInfo("tunnel_status").display, "Работает");
 assert.notEqual(panel._roleInfo("tunnel_status").tone, "active");
 if (name === "status-selector-unconfirmed") {
  assert.equal(data.last_route_change.at, before.last_route_change.at);
  assert.equal(panel._roleInfo("last_route_change").display, before.last_route_change.at);
  assert.equal(panel._roleInfo("active_route").display, "Источник недоступен");
  assert.equal(panel._heroStatus().tone, "bad");
 } else {
  assert.equal(panel._roleInfo("active_route").display, "direct");
  assert.equal(panel._roleInfo("tunnel_status").display, "Остановлено");
  assert.equal(panel._heroStatus().tone, "warn");
 }
}
console.log("Authoritative gateway tunnel and confirmed change observations passed");
